from slow_network import CDP, OUT
import json, time, urllib.request, base64
with urllib.request.urlopen('http://127.0.0.1:9223/json') as response:
    c=CDP(next(t for t in json.load(response) if t['type']=='page')['webSocketDebuggerUrl'])
c.call('Page.enable'); c.call('Runtime.enable')
c.call('Emulation.setDeviceMetricsOverride',width=1440,height=1000,deviceScaleFactor=1,mobile=False)
c.call('Page.navigate',url='http://127.0.0.1:8766/index.html')
time.sleep(2)
c.evaluate("document.querySelector('.campaign-proof').scrollIntoView()")
time.sleep(3)
r={'counters':c.evaluate("[...document.querySelectorAll('[data-count]')].map(e=>e.parentElement.textContent)"),'heroBlur':c.evaluate("[...document.querySelectorAll('.hero-art,.hero-art *')].filter(e=>getComputedStyle(e).filter.includes('blur')||getComputedStyle(e).backdropFilter!=='none').length")}
c.call('Page.navigate',url='http://127.0.0.1:8766/gallery.html')
time.sleep(2)
c.call('Input.dispatchKeyEvent',type='keyDown',key='Tab',code='Tab',windowsVirtualKeyCode=9)
c.call('Input.dispatchKeyEvent',type='keyUp',key='Tab',code='Tab',windowsVirtualKeyCode=9)
c.evaluate("document.querySelector('.morph-photo').scrollIntoView({block:'center'});document.querySelector('.morph-photo').focus()")
time.sleep(1)
r['focusMorph']=c.evaluate("({radius:getComputedStyle(document.querySelector('.morph-photo')).borderRadius,zoom:getComputedStyle(document.querySelector('.morph-photo img')).transform})")
box=c.evaluate("(()=>{const r=document.querySelector('.morph-photo').getBoundingClientRect();return {x:r.x+r.width/2,y:Math.max(10,r.y+100)}})()")
c.call('Input.dispatchMouseEvent',type='mouseMoved',**box)
time.sleep(1)
(OUT/'gallery-morph.png').write_bytes(base64.b64decode(c.call('Page.captureScreenshot',format='png')['data']))
r['hoverMorph']=c.evaluate("getComputedStyle(document.querySelector('.morph-photo')).borderRadius")
c.evaluate("document.querySelector('[data-gallery-filter=party]').click()")
time.sleep(1)
r['filterVisible']=c.evaluate("[...document.querySelectorAll('[data-category]')].filter(e=>!e.hidden).every(e=>e.dataset.category==='party')")
r['errors']=c.evaluate('window.auditErrors||[]')
(OUT/'arch-behavior.json').write_text(json.dumps(r,indent=2));print(json.dumps(r))
c.call('Emulation.setDeviceMetricsOverride',width=768,height=1000,deviceScaleFactor=1,mobile=False)
c.call('Emulation.setEmulatedMedia',features=[{'name':'prefers-reduced-motion','value':'reduce'}])
c.call('Page.navigate',url='http://127.0.0.1:8766/index.html')
time.sleep(4)
c.evaluate("document.querySelectorAll('[data-hero-dot]')[1].click()")
time.sleep(3)
(OUT/'arch-768-real.png').write_bytes(base64.b64decode(c.call('Page.captureScreenshot',format='png')['data']))
c.call('Browser.close')
